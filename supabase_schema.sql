DROP POLICY IF EXISTS "Allow backend API access to users" ON public.users;
CREATE POLICY "Allow backend API access to users" ON public.users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow backend API access to preferences" ON public.preferences;
CREATE POLICY "Allow backend API access to preferences" ON public.preferences FOR ALL USING (true) WITH CHECK (true);

-- Allow public read access to all F1 data tables
DO $$ 
DECLARE
    tbl text;
BEGIN
    FOR tbl IN 
        SELECT tablename 
        FROM pg_tables 
        WHERE schemaname = 'public' 
          AND tablename NOT IN ('users', 'preferences')
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Allow public read access" ON public.%I;', tbl);
        EXECUTE format('CREATE POLICY "Allow public read access" ON public.%I FOR SELECT USING (true);', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "Allow service role write access" ON public.%I;', tbl);
        EXECUTE format('CREATE POLICY "Allow service role write access" ON public.%I FOR ALL USING (true) WITH CHECK (true);', tbl);
    END LOOP;
END $$;
